CREATE TABLE IF NOT EXISTS public.users (
    user_id text PRIMARY KEY,
    name text NOT NULL,
    department text NOT NULL DEFAULT '',
    photo_path text NOT NULL DEFAULT '',
    encoding jsonb,
    created_at text NOT NULL DEFAULT now()::text
);

CREATE TABLE IF NOT EXISTS public.attendance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint UNIQUE,
    user_id text NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    name text NOT NULL,
    date text NOT NULL,
    time text NOT NULL,
    status text NOT NULL DEFAULT 'Present',
    marked_at text NOT NULL DEFAULT now()::text,
    lat double precision,
    lng double precision,
    verified boolean
);

CREATE INDEX IF NOT EXISTS attendance_date_time_idx
    ON public.attendance (date DESC, time DESC);
CREATE INDEX IF NOT EXISTS attendance_user_date_idx
    ON public.attendance (user_id, date);
CREATE UNIQUE INDEX IF NOT EXISTS attendance_one_per_user_per_day_idx
    ON public.attendance (user_id, date)
    WHERE source_id IS NULL;

CREATE TABLE IF NOT EXISTS public.notification_settings (
    key text PRIMARY KEY,
    value text NOT NULL DEFAULT ''
);

